#!/usr/bin/env python3
"""bench/run.py — drive every kernel test, snapshot results to JSON.

Usage:
    python3 bench/run.py [--phase N] [--params "ICACHE_LINES=16 COALESCE=1"] [tests...]
    python3 bench/run.py --xf --label xf-matmul    # or xf-mlp

Each test writes its own JSON via runner.write_bench_result(); this driver
re-runs the regression and aggregates into bench/phase-N.json.

--xf runs test/test_xf_bench.py (bench `<b>` from label `xf-<b>`) under every
XF_CONFIGS build, writes bench/<label>.json and regenerates docs/xf-bench.md
from every bench/xf-*.json. Each row's outputs are checked bit-exact in the run.
"""
from __future__ import annotations
import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_TESTS = [
    "matadd", "matmul", "vector_dot", "relu", "conv1d",
    "transpose", "divergent_relu", "tiled_matmul",
]
XF_CONFIGS = ["", "COALESCE=1", "DCACHE_LINES=16", "COALESCE=1 DCACHE_LINES=16"]
XF_COLS = ["cycles", "data_mem_requests", "data_mem_requests_coalesced", "dcache_hits", "dcache_misses"]


def iv(params: str) -> str:
    return " ".join(f"-Pgpu.{p}" for p in params.split())


def run_one(name: str, params: str) -> dict | None:
    test_file = ROOT / "test" / f"test_{name}.py"
    if not test_file.exists():
        return None
    env = {**os.environ, "BENCH_RESULTS": "1"}
    cmd = ["make", f"test_{name}", f"PARAMS={iv(params)}"]
    res = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, env=env)
    passed = res.returncode == 0
    result_file = ROOT / "bench" / "results" / f"{name}.json"
    metrics = {}
    if passed and result_file.exists():
        metrics = json.loads(result_file.read_text())
    metrics["passed"] = passed
    metrics["name"] = name
    if not passed:
        metrics["stdout_tail"] = res.stdout.splitlines()[-12:]
    return metrics


def run_xf(bench: str, label: str) -> int:
    rows, fails = [], 0
    for params in XF_CONFIGS:
        env = {**os.environ, "BENCH_RESULTS": "1", "COCOTB_TEST_FILTER": f"bench_{bench}$"}
        res = subprocess.run(["make", "test_xf_bench", f"PARAMS={iv(params)}"],
                             cwd=ROOT, capture_output=True, text=True, env=env)
        out = ROOT / "bench" / "results" / f"xf_{bench}.json"
        ok = res.returncode == 0 and out.exists()
        print(f"  [{'PASS' if ok else 'FAIL'}] {bench} {params or 'default'}")
        if not ok:
            print("\n".join(res.stdout.splitlines()[-12:]))
            fails += 1
            continue
        rows += [{"params": params, **r} for r in json.loads(out.read_text())["rows"]]
        out.unlink()
    if fails:
        return 1
    path = ROOT / "bench" / f"{label}.json"
    path.write_text(json.dumps({"bench": bench, "configs": XF_CONFIGS, "rows": rows}, indent=2, sort_keys=True) + "\n")
    print(f"Wrote {path}")
    write_xf_doc()
    return 0


def write_xf_doc():
    lines = ["# xf benchmarks", "",
             "Generated by `python3 bench/run.py --xf --label xf-<bench>` from `bench/xf-*.json`; do not edit.",
             "Cycles per launch at `WORD_BITS=32`, every output checked bit-exact in the same run.",
             "Requests, coalesced requests and L1-D hit/miss are from the `COALESCE=1 DCACHE_LINES=16` build.", ""]
    for f in sorted((ROOT / "bench").glob("xf-*.json")):
        d = json.loads(f.read_text())
        key = lambda r: (r["case"], r["kind"])
        by = {(key(r), r["params"]): r for r in d["rows"]}
        cases = list(dict.fromkeys(key(r) for r in d["rows"]))
        if d["bench"] == "mlp":
            cases.sort(key=lambda c: c[1])
            for kind in dict.fromkeys(k for _, k in cases):
                for p in d["configs"]:
                    by[(("total", kind), p)] = {c: sum(by[(cs, p)][c] for cs in cases if cs[1] == kind) for c in XF_COLS}
                cases.append(("total", kind))
        lines += [f"## {d['bench']} (`bench/{f.name}`)", "",
                  "| case | kind | " + " | ".join(f"cycles {p or 'default'}" for p in d["configs"]) +
                  " | mem req | coalesced | L1-D hit/miss |",
                  "|---|---|" + "---:|" * (len(d["configs"]) + 3)]
        for c in cases:
            r = by[(c, d["configs"][-1])]
            lines.append(f"| {c[0]} | {c[1]} | " + " | ".join(str(by[(c, p)]["cycles"]) for p in d["configs"]) +
                         f" | {r['data_mem_requests']} | {r['data_mem_requests_coalesced']} | "
                         f"{r['dcache_hits']}/{r['dcache_misses']} |")
        lines.append("")
    (ROOT / "docs" / "xf-bench.md").write_text("\n".join(lines))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--phase", type=int, default=0)
    ap.add_argument("--params", default="")
    ap.add_argument("--label", default=None)
    ap.add_argument("--xf", action="store_true")
    ap.add_argument("tests", nargs="*", default=DEFAULT_TESTS)
    args = ap.parse_args()
    if args.xf:
        if not (args.label or "").startswith("xf-"):
            ap.error("--xf needs --label xf-<bench>")
        return run_xf(args.label[3:], args.label)

    rollup = {"phase": args.phase, "params": args.params, "results": []}
    fails = 0
    for t in args.tests:
        m = run_one(t, args.params)
        if m is None:
            print(f"  -- {t}: no test file, skipping")
            continue
        marker = "PASS" if m.get("passed") else "FAIL"
        cycles = m.get("cycles", "?")
        mreqs  = m.get("data_mem_requests", "?")
        coal   = m.get("data_mem_requests_coalesced", "?")
        ihits  = m.get("icache_hits", "?")
        imiss  = m.get("icache_misses", "?")
        dhits  = m.get("dcache_hits", "?")
        dmiss  = m.get("dcache_misses", "?")
        print(f"  [{marker}] {t:18s} cycles={cycles}  mem_req={mreqs}  coal={coal}  ic={ihits}/{imiss}  dc={dhits}/{dmiss}")
        rollup["results"].append(m)
        if not m.get("passed"):
            fails += 1

    label = args.label or f"phase-{args.phase}"
    out = ROOT / "bench" / f"{label}.json"
    out.write_text(json.dumps(rollup, indent=2, sort_keys=True))
    print(f"\nWrote {out}")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
